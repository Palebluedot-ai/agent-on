// Optional browser smoke: node dashboard_browser.cjs URL PLAYWRIGHT_MODULE SCREENSHOT
// Exercises the live read-only view; no dispatch, hooks or Git mutations.
const {chromium}=require(process.argv[3]||'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:process.env.AGENT_ON_BROWSER_CHANNEL||'chrome'});
  try {
    const page=await browser.newPage({viewport:{width:1360,height:1000}});
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(process.argv[2]);
    await page.waitForFunction(()=>document.getElementById('treeCount').textContent!=='—');
    const state=await page.evaluate(async()=>{
      const response=await fetch('/api/status',{headers:{'X-Agent-On':'dashboard'}});
      return response.json();
    });
    const api=new URL('/api/status',process.argv[2]).href;
    if((await page.request.get(api)).status()!==403)throw Error('API accepts missing header');
    if((await page.request.get(api,{headers:{'X-Agent-On':'dashboard',Origin:'https://evil.test'}})).status()!==403)throw Error('API accepts cross-origin request');
    if((await page.request.post(api)).status()!==405)throw Error('API accepts mutation method');
    if(Number(await page.locator('#treeCount').textContent())!==state.worktrees.length)throw Error('worktree count mismatch');
    if(state.config.data.enabled===false && !(await page.locator('#attention').textContent()).includes('巡逻未启用'))throw Error('missing coverage gap');
    if(state.landing_age_seconds>120 && !(await page.locator('#attention').textContent()).includes('PR 取证'))throw Error('missing stale evidence');
    if(await page.locator('#tasks [data-lane]').count()!==4)throw Error('missing status lanes');
    if(!(await page.locator('#activityStatus').textContent()).includes(state.activity?.available?'已有活动回传':'窗口活动未知'))throw Error('native activity coverage misreported');
    const active=state.patrol.data?.tasks?.filter(t=>!['released','reclaimed'].includes(t.state))||[];
    if(await page.locator('#tasks .task-card').count()!==active.length)throw Error('task card count mismatch');
    if(await page.locator('#archive').getAttribute('open')!==null)throw Error('history should start collapsed');
    await page.locator('#wall').click();
    if(!(await page.locator('body').getAttribute('class')||'').includes('wall'))throw Error('wall mode missing');
    await page.locator('#wall').click();
    await page.locator('#filter').fill('this-task-does-not-exist');
    if(await page.locator('#trees td').count())throw Error('filter did not filter');
    await page.locator('#filter').fill('');
    await page.locator('#refresh').click();
    await page.waitForTimeout(200);
    await page.screenshot({path:process.argv[4]||'/tmp/agent-on-dashboard.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('mobile overflow');
    // Synthetic browser responses only: never register fake Claude work in the user's ledger.
    const fixture=structuredClone(state),now=new Date().toISOString();
    const task=(id,host,status,title)=>({id,goal:'full scope '+id,title,state:status,paths:['src/'+id],worktree:state.repo,created_at:now,progress:{at:now,note:'具体下一步'},last_reporter:host?{host,session_id:'fixture-'+host}:null});
    fixture.patrol.data.tasks=[task('codex-ui','codex','working','看板界面'),task('claude-tests','claude','blocked','回归测试'),task('review','claude','reported','等待验收'),task('legacy',null,'queued','旧任务'),task('done','codex','released','历史结项')];
    fixture.patrol.data.sessions=[];fixture.patrol.data.results=[];
    fixture.activity={enabled:true,available:true,windows:[{id:'fixture-window',host:'codex',session_id:'fixture-window',task:'codex-ui',goal:'实现回执接线',paths:['src/activity.rs'],state:'working',source:'native-hook',at:now}]};
    await page.route('**/api/status',route=>route.fulfill({json:fixture}));
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.querySelector('[data-task="claude-tests"]'));
    if(!(await page.locator('#windowActivity').textContent()).includes('实现回执接线'))throw Error('window goal missing');
    fixture.activity.windows[0].state='turn-finished';await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.getElementById('windowActivity').textContent.includes('本轮结束'));
    if(!await page.locator('[data-lane="working"] [data-task="codex-ui"]').count())throw Error('activity changed canonical task stage');
    if(await page.locator('#tasks .task-card').count()!==4)throw Error('mixed host tasks missing');
    if(!(await page.locator('[data-task="codex-ui"] .host-line').textContent()).includes('Codex'))throw Error('Codex source missing');
    if(!(await page.locator('[data-task="claude-tests"] .host-line').textContent()).includes('Claude'))throw Error('Claude source missing');
    if(!(await page.locator('[data-task="legacy"] .host-line').textContent()).includes('未关联工具'))throw Error('unknown host invented');
    await page.locator('[data-host="claude"]').click();
    if(await page.locator('#tasks .task-card').count()!==2)throw Error('host filter failed');
    await page.locator('[data-host="all"]').click();
    fixture.patrol.data.tasks[0].state='reported';
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>!document.querySelector('[data-lane="working"] .task-card'));
    if(!(await page.locator('[data-lane="working"]').textContent()).includes('窗口活动未知'))throw Error('empty task stage mistaken for no active window');
    fixture.patrol.data.tasks[0].state='working';
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.querySelector('[data-lane="working"] .task-card'));
    const details=page.locator('[data-task="claude-tests"] .task-details');
    await details.locator('summary').click();
    fixture.patrol.data.tasks[1].state='reported';
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.querySelector('[data-lane="reported"] [data-task="claude-tests"]'));
    if(!(await details.getAttribute('open')!==null))throw Error('refresh lost expanded task');
    if(await page.locator('[data-lane="blocked"] .task-card').count())throw Error('stale lane membership');
    fixture.patrol.data.tasks[1].title='<img src=x onerror=window.__xss=1>';
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.querySelector('[data-task="claude-tests"] h3').textContent.includes('<img'));
    if(await page.locator('#tasks img').count()||await page.evaluate(()=>window.__xss))throw Error('task title executed HTML');
    await page.locator('#filter').fill('this-task-does-not-exist');
    if(await page.locator('#tasks .task-card').count())throw Error('task search failed');
    await page.locator('#filter').fill('');
    fixture.patrol={available:false,error:'fixture damaged ledger'};
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.getElementById('taskCount').textContent==='—');
    if(!(await page.locator('#tasks').textContent()).includes('记录不可读'))throw Error('unavailable task ledger appears empty/healthy');
    await page.unroute('**/api/status');
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.getElementById('taskCount').textContent!=='—');
    await page.route('**/api/status',route=>route.abort());
    await page.locator('#refresh').click();
    await page.waitForFunction(()=>document.getElementById('connection').textContent.includes('连接已断开'));
    if(Number(await page.locator('#treeCount').textContent())!==state.worktrees.length)throw Error('disconnect lost last observation');
    if(errors.length)throw Error(errors.join('\n'));
    console.log(JSON.stringify({browser:'PASS',worktrees:state.worktrees.length,tasks:state.patrol.data?.tasks?.length??null,mixed_host_fixture:'PASS',dynamic_lanes:'PASS',console_errors:errors}));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
